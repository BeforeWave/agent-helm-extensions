export const helmUiDictionaries = { zh, en } as const
export type HelmLocale = keyof typeof helmUiDictionaries
export type HelmTranslate = (key: HelmLocaleKey, params?: Record<string, string | number>) => string

export function resolveHelmLocale(language: string | null | undefined): HelmLocale {
  return language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function createHelmTranslate(locale: HelmLocale): HelmTranslate {
  const dictionary = helmUiDictionaries[locale] as Record<HelmLocaleKey, string>
  return (key, params) => {
    let value = dictionary[key] ?? String(key)
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement))
      }
    }
    return value
  }
}

export function getBrowserLanguage(): string {
  try {
    if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) {
      const language = chrome.i18n.getUILanguage()
      if (language) return language
    }
  } catch {
    // Fall through to preview/test overrides and navigator.
  }
  try {
    if (typeof window !== 'undefined') {
      const previewLocale = new URLSearchParams(window.location.search).get('locale')
      if (previewLocale === 'zh') return 'zh-CN'
      if (previewLocale === 'en') return 'en'
    }
  } catch {
    // Ignore malformed/non-browser preview locations.
  }
  return typeof navigator !== 'undefined' && navigator.language ? navigator.language : 'en'
}

export const helmLocale: HelmLocale = resolveHelmLocale(getBrowserLanguage())
export const t = createHelmTranslate(helmLocale)
export const dateLocale = helmLocale === 'zh' ? 'zh-CN' : 'en-US'

if (typeof document !== 'undefined') document.documentElement.lang = dateLocale

